if __name__ == "__main__":
    print("Starting advanced structural cleaning & topic consolidation...")
    
    removed_ids = set()
    id_replacements = {}
    school_unified_id = None
    cleaned_map_rows = []
    
    # Step 1: Parse map.txt, eliminate noise, and dynamically unify school terms
    with open(INPUT_MAP, 'r', encoding='utf-8-sig') as f:
        reader = csv.reader(f, delimiter='\t')
        header = next(reader)
        cleaned_map_rows.append(header)
        
        for row in reader:
            if not row:
                continue
            node_id = row[0]
            label = row[1]
            url = row[2] if len(row) > 2 else ""
            desc = row[3] if len(row) > 3 else ""
            
            # Identify if the row is a document metadata or a term node
            is_article = "Scraped Publication" in desc or url.startswith("http")
            
            if is_article:
                cleaned_map_rows.append(row)
            else:
                if label in WORDS_TO_REMOVE:
                    removed_ids.add(node_id)
                elif label in SCHOOL_WORDS:
                    if school_unified_id is None:
                        school_unified_id = node_id
                        row[1] = "בית_ספר"
                        cleaned_map_rows.append(row)
                    else:
                        # Remap this ID to the first 'school' anchor ID
                        id_replacements[node_id] = school_unified_id
                else:
                    cleaned_map_rows.append(row)

    print(f"Purged {len(removed_ids)} generic words. Unifying school variants into anchor ID: {school_unified_id}")

    # Step 2: Parse network.txt and aggregate weights for collapsed connections
    network_edges = {}
    
    with open(INPUT_NETWORK, 'r', encoding='utf-8') as f:
        reader = csv.reader(f, delimiter='\t')
        for row in reader:
            if not row:
                continue
            src = row[0]
            tgt = row[1]
            weight = int(row[2]) if len(row) > 2 else 1
            
            # Drop line if it links to a deleted word
            if src in removed_ids or tgt in removed_ids:
                continue
                
            # Apply the unified topic remapping
            if src in id_replacements:
                src = id_replacements[src]
            if tgt in id_replacements:
                tgt = id_replacements[tgt]
                
            # Prevent self-loops (e.g., if 'בית' and 'ספר' were linked within the same context)
            if src == tgt:
                continue
                
            # Aggregate weights dynamically
            edge_key = (src, tgt)
            network_edges[edge_key] = network_edges.get(edge_key, 0) + weight

    # Step 3: Write outputs to clean files
    with open(OUTPUT_MAP, 'w', newline='', encoding='utf-8-sig') as f:
        writer = csv.writer(f, delimiter='\t')
        writer.writerows(cleaned_map_rows)
        
    with open(OUTPUT_NETWORK, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f, delimiter='\t')
        for (src, tgt), total_weight in network_edges.items():
            writer.writerow([src, tgt, total_weight])
            
    print("🏆 Success! New optimized files created: map_cleaned.txt and network_cleaned.txt")